                    <div class="history-timeline">
                        <article class="history-milestone"><span class="history-year">1981</span><p>Under University President Dr. Manuel T. Corpuz and pioneer Dean Engr. Jose Borja, Bachelor of Science in Civil Engineering was the college's first program.</p></article>
                        <article class="history-milestone"><span class="history-year">1988–1990</span><p>Under Dean Dominador T. Agatep, Electrical Engineering and Agricultural Engineering were introduced in 1988, followed by Electronics and Communications Engineering and Computer Engineering in 1990.</p></article>
                        <article class="history-milestone"><span class="history-year">1997</span><p>Under Dean Diosdado Dimalanta, Bachelor of Science in Chemical Engineering was added to the college's program offerings.</p></article>
                        <article class="history-milestone"><span class="history-year">2019–2022</span><p>Bachelor of Science in Architecture was offered in 2019, followed by Bachelor of Science in Geodetic Engineering in 2022. The expansion of programs helped the university respond to the evolving development needs of the region.</p></article>
